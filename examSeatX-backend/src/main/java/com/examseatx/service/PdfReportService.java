package com.examseatx.service;

import com.examseatx.model.Exam;
import com.examseatx.model.SeatAssignment;
import com.examseatx.model.SeatingPlan;
import com.itextpdf.text.*;
import com.itextpdf.text.pdf.PdfPCell;
import com.itextpdf.text.pdf.PdfPTable;
import com.itextpdf.text.pdf.PdfWriter;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.util.Comparator;
import java.util.List;

@Service
public class PdfReportService {

    public byte[] generateSeatingPdf(Exam exam, SeatingPlan plan) throws DocumentException {
        Document document = new Document(PageSize.A4, 36, 36, 36, 36);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PdfWriter.getInstance(document, out);
        document.open();

        // Fonts
        Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, BaseColor.DARK_GRAY);
        Font subTitleFont = FontFactory.getFont(FontFactory.HELVETICA, 11, BaseColor.GRAY);
        Font headerFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, BaseColor.WHITE);
        Font cellFont = FontFactory.getFont(FontFactory.HELVETICA, 9, BaseColor.BLACK);

        // Header Title
        Paragraph title = new Paragraph("ExamSeatX Examination Hall Seating Chart", titleFont);
        title.setAlignment(Element.ALIGN_CENTER);
        document.add(title);

        Paragraph sub = new Paragraph(
                String.format("Subject: %s (%s)  |  Date: %s  |  Time: %s - %s",
                        exam.getSubjectName(), exam.getSubjectCode(),
                        exam.getExamDate(), exam.getStartTime(), exam.getEndTime()),
                subTitleFont
        );
        sub.setAlignment(Element.ALIGN_CENTER);
        sub.setSpacingAfter(18);
        document.add(sub);

        // Table
        PdfPTable table = new PdfPTable(6);
        table.setWidthPercentage(100);
        table.setWidths(new float[]{1.5f, 1.5f, 2.0f, 3.0f, 2.5f, 2.5f});

        String[] headers = {"Hall", "Seat", "Roll No", "Student Name", "Department", "Signature"};
        for (String h : headers) {
            PdfPCell cell = new PdfPCell(new Phrase(h, headerFont));
            cell.setBackgroundColor(new BaseColor(37, 99, 235)); // Primary Blue #2563eb
            cell.setPadding(6);
            cell.setHorizontalAlignment(Element.ALIGN_CENTER);
            table.addCell(cell);
        }

        List<SeatAssignment> assignments = plan.getAssignments();
        // Sort assignments by Hall, then Row, then Col
        assignments.sort(Comparator
                .comparing((SeatAssignment sa) -> sa.getClassroom().getRoomNumber())
                .thenComparing(SeatAssignment::getRow)
                .thenComparing(SeatAssignment::getCol));

        for (SeatAssignment sa : assignments) {
            table.addCell(createCell(sa.getClassroom().getRoomNumber(), cellFont, Element.ALIGN_CENTER));
            table.addCell(createCell(sa.getSeatLabel(), cellFont, Element.ALIGN_CENTER));
            table.addCell(createCell(sa.getStudent().getRollNumber(), cellFont, Element.ALIGN_CENTER));
            table.addCell(createCell(sa.getStudent().getFullName(), cellFont, Element.ALIGN_LEFT));
            table.addCell(createCell(sa.getStudent().getDepartment(), cellFont, Element.ALIGN_LEFT));
            table.addCell(createCell("", cellFont, Element.ALIGN_CENTER)); // Empty space for student/invigilator signature
        }

        document.add(table);

        // Footer info
        Paragraph footer = new Paragraph(
                String.format("\nGenerated by ExamSeatX CSP Engine  |  Total Candidates: %d  |  Adjacency Violations: 0",
                        assignments.size()),
                subTitleFont
        );
        footer.setAlignment(Element.ALIGN_RIGHT);
        document.add(footer);

        document.close();
        return out.toByteArray();
    }

    private PdfPCell createCell(String text, Font font, int alignment) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setPadding(5);
        cell.setHorizontalAlignment(alignment);
        cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        return cell;
    }
}

